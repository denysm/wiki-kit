#!/usr/bin/env python3
"""Generate the tool catalog's task index, area pages and science section pages from its cards.

Usage:
  catalog_index.py CATALOG              write the generated pages under CATALOG/wiki/topics/
  catalog_index.py CATALOG --check      exit 1 when a generated page differs from what the cards give
  catalog_index.py CATALOG --validate [CARD ...]
                                        check card structure (all cards when none given); exit 1 on findings

The card is the only master of a part's status (docs/catalog-design.md, builder's
call 2). This script reads every card in `wiki/references/` (frontmatter `title`,
`areas`, `kind`, `sources`, optional `science_sections`; the tables of "Tasks it
serves" and "What's inside"), `schema.md` (tables "Areas" and "Science
sections") and the parts lists in `raw/data/` that cards cite, and writes:

  wiki/topics/task-index.md                 one table per area: Task | Go to | Status | Not this, because
  wiki/topics/area-<slug>.md                Card | Part | Status (area-science.md lists the sections)
  wiki/topics/area-science-<section>.md     Part | Card | Status | One line

Each page cites in `sources:` the union of the sources of the cards it lists,
says it is generated, and adds no numbers or dates of its own (builder's call 3).
Pages for areas or sections with no card are not written; a stale generated page
is deleted. Deterministic; stdlib only.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

STATUSES = ("listed", "candidate", "tried", "in use", "method taken", "reference", "rejected")
KINDS = ("plugin", "skill-collection", "library", "app", "cli", "model", "runtime", "pattern")
COLLECTION_KINDS = ("plugin", "skill-collection")
SECTIONS = ("Tasks it serves", "Run it here", "What's inside", "Tried", "Verdict", "See Also", "Sources")
REQUIRED = ("title", "category", "sources", "created", "updated", "tags", "confidence", "volatility",
            "verified", "summary", "areas", "kind", "version", "licence", "desk_checked")
MARKER = "Generated by `scripts/catalog_index.py` from the cards; do not edit by hand."
CONF_ORDER = {"low": 0, "medium": 1, "high": 2}
LINK = re.compile(r"\]\(([^)\s]+)\)")


# ---------- parsing ----------

def split_front(text: str) -> tuple[dict, list[str], str]:
    """(fields, raw frontmatter lines, body). Reads scalars, inline lists and block lists."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, [], text
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, [], text
    raw, fields, key = lines[1:end], {}, None
    for line in raw:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            if " #" in val and not val.startswith(('"', "'")):
                val = val.split(" #", 1)[0].rstrip()
            if val.startswith("[") and val.endswith("]"):
                fields[key] = [v.strip().strip("\"'") for v in val[1:-1].split(",") if v.strip()]
            elif val == "":
                fields[key] = []
            else:
                fields[key] = val[1:-1] if len(val) > 1 and val[0] == val[-1] and val[0] in "\"'" else val
        elif key and re.match(r"^\s+-\s+", line) and isinstance(fields.get(key), list):
            fields[key].append(re.sub(r"^\s+-\s+", "", line).strip().strip("\"'"))
    return fields, raw, "\n".join(lines[end + 1:])


def sections_of(body: str) -> list[tuple[str, str]]:
    out, title, buf = [], None, []
    for line in body.splitlines():
        m = re.match(r"^## (.+?)\s*$", line)
        if m:
            if title is not None:
                out.append((title, "\n".join(buf)))
            title, buf = m.group(1), []
        elif title is not None:
            buf.append(line)
    if title is not None:
        out.append((title, "\n".join(buf)))
    return out


def split_row(line: str) -> list[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    cells, cur, tick = [], "", False
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            cur += "\\|"
            i += 2
            continue
        if c == "`":
            tick = not tick
        if c == "|" and not tick:
            cells.append(cur.strip())
            cur = ""
        else:
            cur += c
        i += 1
    cells.append(cur.strip())
    return cells


def table_of(text: str) -> tuple[list[str], list[list[str]]]:
    """The first Markdown table in a section: (header, rows)."""
    lines = [l for l in text.splitlines() if l.strip().startswith("|")]
    if len(lines) < 2:
        return [], []
    header = split_row(lines[0])
    rows = [split_row(l) for l in lines[2:]]
    return header, [r + [""] * (len(header) - len(r)) for r in rows]


def md_table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("-" * (len(h) + 2) for h in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def strip_paren(s: str) -> str:
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r"\s*\([^()]*\)", "", s)
    return s


def norm(s: str) -> str:
    return " ".join(strip_paren(s).split()).lower()


def ticks(s: str) -> list[str]:
    return re.findall(r"`([^`]+)`", s)


# ---------- model ----------

class Schema:
    def __init__(self, path: Path):
        text = path.read_text(encoding="utf-8")
        secs = dict(sections_of(split_front(text)[2]))
        self.areas = {}
        for r in table_of(secs.get("Areas", ""))[1]:
            self.areas[r[0]] = {"title": r[1], "scope": r[2],
                                "neighbours": [n.strip() for n in r[3].split(",") if n.strip()]}
        self.science = {}
        for r in table_of(secs.get("Science sections", ""))[1]:
            self.science[r[0]] = {"title": r[1], "heading": r[2]}
        if not self.areas:
            raise SystemExit(f"error: no Areas table in {path}")

    def section_for_heading(self, heading: str) -> str | None:
        h = heading.strip().lower()
        return next((s for s, d in self.science.items() if d["heading"].lower() == h), None)


class Card:
    def __init__(self, path: Path, root: Path):
        self.path, self.root = path, root
        self.text = path.read_text(encoding="utf-8")
        self.fm, self.fm_raw, self.body = split_front(self.text)
        self.slug = path.stem
        self.title = str(self.fm.get("title", self.slug))
        self.kind = str(self.fm.get("kind", ""))
        self.areas = list(self.fm.get("areas") or [])
        self.sources = list(self.fm.get("sources") or [])
        self.science_sections = list(self.fm.get("science_sections") or [])
        self.secs = sections_of(self.body)
        d = dict(self.secs)
        self.tasks_header, self.tasks = table_of(d.get("Tasks it serves", ""))
        self.inside_header, self.inside = table_of(d.get("What's inside", ""))
        self.tried_header, self.tried = table_of(d.get("Tried", ""))
        self.parts_lists = [s for s in self.sources if s.startswith("raw/data/") and "-parts-" in s]
        self.listed = {}  # name -> (description, [README sections]) from parts lists
        for pl in self.parts_lists:
            f = root / pl
            if f.exists():
                for r in table_of(split_front(f.read_text(encoding="utf-8"))[2])[1]:
                    names = ticks(r[0])
                    if names:
                        self.listed[names[0]] = (r[2], [x.strip() for x in r[3].split(";") if x.strip() and x.strip() != "none"])

    def link(self, from_dir: str) -> str:
        return f"[{self.title}]({from_dir}{self.slug}.md)"

    def status_col(self) -> int:
        return self.inside_header.index("Status") if "Status" in self.inside_header else 2

    def match_parts(self, cell: str) -> list[tuple[str, str, str]]:
        """Parts of What's inside (or of a parts list) named by a Tasks it serves Part cell:
        [(part cell, status, what it does or one line)]."""
        sc = self.status_col()
        rows = {norm(r[0]): r for r in self.inside}
        cell = re.sub(r"^not this:\s*", "", cell, flags=re.I)
        found = []
        whole = norm(cell)
        if whole in rows:
            r = rows[whole]
            return [(r[0], r[sc], r[1])]
        for piece in [p for p in re.split(r",\s*", strip_paren(cell)) if p.strip()]:
            key = norm(piece)
            if key in rows:
                r = rows[key]
                found.append((r[0], r[sc], r[1]))
                continue
            pref = [r for k, r in rows.items() if k.startswith(key + " ") or k == key]
            tk = ticks(piece)
            if not pref and tk:
                pref = [r for r in self.inside if ticks(r[0])[:1] == tk[:1] and norm(r[0]) == norm(f"`{tk[0]}`")]
            if pref:
                r = pref[0]
                found.append((r[0], r[sc], r[1]))
            elif tk and tk[0] in self.listed:
                found.append((f"`{tk[0]}`", "listed", self.listed[tk[0]][0]))
        return found

    def task_rows(self) -> list[dict]:
        out = []
        for r in self.tasks:
            task, part, area = r[0], r[1], r[2].strip()
            out.append({"task": task, "part": part, "area": area, "matches": self.match_parts(part)})
        return out


def load(root: Path) -> tuple[Schema, list[Card]]:
    schema = Schema(root / "schema.md")
    refs = root / "wiki" / "references"
    cards = [Card(p, root) for p in sorted(refs.glob("*.md")) if p.name != "_index.md"] if refs.exists() else []
    return schema, cards


# ---------- validation ----------

def validate(card: Card, schema: Schema) -> list[str]:
    f, out = card.fm, []
    for k in REQUIRED:
        if k not in f or f[k] in ("", []):
            out.append(f"frontmatter: `{k}` missing")
    if not (f.get("repo") or f.get("url")):
        out.append("frontmatter: neither `repo` nor `url`")
    if f.get("category") not in (None, "reference"):
        out.append("frontmatter: category must be `reference`")
    if card.kind and card.kind not in KINDS:
        out.append(f"frontmatter: kind `{card.kind}` not one of {', '.join(KINDS)}")
    if not any(re.match(r'^version:\s*["\']', l) for l in card.fm_raw):
        out.append("frontmatter: `version` must be quoted")
    for a in card.areas:
        if a not in schema.areas:
            out.append(f"frontmatter: area `{a}` not in schema.md")
    for s in card.science_sections:
        if s not in schema.science:
            out.append(f"frontmatter: science section `{s}` not in schema.md")
    for s in card.sources:
        if not (card.root / s).exists():
            out.append(f"sources: `{s}` does not exist")
    # abstract and section order
    before = card.body.split("\n## ", 1)[0]
    if not re.search(r"^> \S", before, re.M):
        out.append("abstract: no `>` paragraph before the first section")
    names = [t for t, _ in card.secs]
    if [n for n in names if n in SECTIONS] != list(SECTIONS):
        out.append(f"sections: need {' / '.join(SECTIONS)} in this order; found {' / '.join(names)}")
    # tasks
    if card.tasks_header[:3] != ["Task", "Part", "Area"]:
        out.append("Tasks it serves: columns must be Task | Part | Area")
    for t in card.task_rows():
        a = t["area"]
        if a.startswith("science-"):
            if a[8:] not in schema.science:
                out.append(f"Tasks it serves: unknown science section `{a}`")
            if "science" not in card.areas:
                out.append(f"Tasks it serves: `{a}` but `science` not in areas")
        elif a not in card.areas:
            out.append(f"Tasks it serves: area `{a}` not in the card's areas")
        if not t["matches"]:
            out.append(f"Tasks it serves: part `{t['part']}` matches no What's inside row or parts-list part")
    # what's inside
    fourth = "Without plugin" if card.kind in COLLECTION_KINDS else "Needs"
    want = ["Part", "What it does", "Status", fourth, "Check when"]
    if card.inside_header != want:
        out.append(f"What's inside: columns must be {' | '.join(want)}")
    sc = card.status_col()
    for r in card.inside:
        if r[sc] not in STATUSES:
            out.append(f"What's inside: `{r[0]}` status `{r[sc]}` is not one of the seven")
        if len(r) > 4 and not r[4].strip():
            out.append(f"What's inside: `{r[0]}` has no Check when")
        if len(r) > 3 and not r[3].strip():
            out.append(f"What's inside: `{r[0]}` has an empty {fourth} cell")
    if len(card.inside) > 40 and not card.parts_lists:
        out.append("What's inside: more than 40 rows; generate a parts list (catalog_parts.py) and keep only non-listed parts")
    # tried
    if card.tried_header and card.tried_header != ["Date", "Task (by kind)", "Part", "Result", "Cost", "Record"]:
        out.append("Tried: columns must be Date | Task (by kind) | Part | Result | Cost | Record")
    tried_text = " ".join(" ".join(r) for r in card.tried)
    for r in card.tried:
        rec = LINK.findall(r[5]) if len(r) > 5 else []
        if not rec or not any("raw/notes/trials/" in x for x in rec):
            out.append(f"Tried: row `{r[0]}` does not link a record in raw/notes/trials/")
    for r in card.inside:
        if r[sc] in ("tried", "in use"):
            names = ticks(r[0]) or [r[0]]
            if not any(n in tried_text for n in names):
                out.append(f"Tried: `{r[0]}` is `{r[sc]}` but has no Tried row")
    # see also and sources
    d = dict(card.secs)
    for a in card.areas:
        if f"area-{a}.md" not in d.get("See Also", ""):
            out.append(f"See Also: no link to area-{a}.md")
    listed = {re.sub(r"^(\.\./)+", "", x) for x in LINK.findall(d.get("Sources", ""))}
    for s in card.sources:
        if s not in listed:
            out.append(f"Sources: `{s}` is in sources: but not in ## Sources")
    for s in sorted(listed - set(card.sources)):
        out.append(f"Sources: `{s}` is in ## Sources but not in sources:")
    return out


# ---------- generation ----------

def page(title, slug_tags, summary, abstract, body_lines, cards, see_also, root_rel="../../") -> str:
    srcs = sorted({s for c in cards for s in c.sources})
    created = min((str(c.fm.get("created", "")) for c in cards), default="")
    updated = max((str(c.fm.get("updated", "")) for c in cards), default="")
    verified = max((str(c.fm.get("verified", "")) for c in cards), default="")
    conf = min((str(c.fm.get("confidence", "medium")) for c in cards), key=lambda x: CONF_ORDER.get(x, 1),
               default="medium")
    fm = ["---", f'title: "{title}"', "category: topic", "sources:"] + [f"  - {s}" for s in srcs] + [
        f"created: {created}", f"updated: {updated}",
        "tags: [" + ", ".join(["catalog", "area"] + slug_tags) + "]",
        f"confidence: {conf}", "volatility: hot", f"verified: {verified}",
        f'summary: "{summary}"', "---", ""]
    body = [f"# {title}", "", f"> {abstract}", "", MARKER, ""] + body_lines + ["", "## See Also", ""]
    body += [f"- {s}" for s in see_also] + ["", "## Sources", ""]
    body += [f"- [{s}]({root_rel}{s})" for s in srcs]
    return "\n".join(fm + body) + "\n"


def dual(slug: str, title: str, path: str) -> str:
    return f"[[{slug}|{title}]] ([{title}]({path}))"


def not_this(task: str, matches) -> tuple[str, str]:
    """(task text, reason) for a Tasks it serves row; reason only for a 'Not this:' row."""
    t = task.strip()
    if not re.match(r"^not this:", t, re.I):
        return t, ""
    t = re.sub(r"^not this:\s*", "", t, flags=re.I)
    m = re.search(r"\s*\bRejected:\s*", t)
    if m:
        return t[:m.start()].rstrip(" ."), t[m.end():].strip()
    return t, "see the card's rejected row"


def generate(root: Path, schema: Schema, cards: list[Card]) -> dict[str, str]:
    pages: dict[str, str] = {}
    by_area: dict[str, list] = {a: [] for a in schema.areas}
    section_cards: dict[str, set] = {s: set() for s in schema.science}
    section_rows: dict[str, list] = {s: [] for s in schema.science}
    index_rows: dict[str, list] = {a: [] for a in schema.areas}
    index_cards: list[Card] = []

    for c in cards:
        index_cards.append(c)
        part_sections: dict[str, set] = {}
        for t in c.task_rows():
            area = t["area"]
            sec = area[8:] if area.startswith("science-") and area[8:] in schema.science else None
            area_slug = "science" if sec or area == "science" else area
            if area_slug not in schema.areas:
                continue
            task, reason = not_this(t["task"], t["matches"])
            status = t["matches"][0][1] if t["matches"] else "unmatched"
            if sec:
                go = f"[{schema.science[sec]['title']}: {t['part']} ({c.title})](area-science-{sec}.md)"
            elif area_slug == "science":
                go = f"[Science: {t['part']} ({c.title})](area-science.md)"
            else:
                go = f"[{c.title}: {t['part']}](../references/{c.slug}.md)"
            index_rows[area_slug].append([task, go, status, reason])
            for pcell, st, _ in t["matches"]:
                if [c, pcell, st] not in by_area[area_slug]:
                    by_area[area_slug].append([c, pcell, st])
                if sec:
                    part_sections.setdefault(pcell, set()).add(sec)
        # science sections of parts
        if "science" in c.areas:
            sc = c.status_col()
            in_card = {}
            for r in c.inside:
                in_card[norm(r[0])] = r
            for r in c.inside:
                secs = set(part_sections.get(r[0], set())) or set(c.science_sections)
                for name in ticks(r[0])[:1]:
                    if name in c.listed:
                        secs |= {s for h in c.listed[name][1] if (s := schema.section_for_heading(h))}
                for s in secs:
                    section_rows[s].append([r[0], c, r[sc], first_sentence(r[1])])
                    section_cards[s].add(c)
            for name, (desc, heads) in sorted(c.listed.items()):
                if norm(f"`{name}`") in in_card:
                    continue
                for s in sorted({x for h in heads if (x := schema.section_for_heading(h))}):
                    section_rows[s].append([f"`{name}`", c, "listed", desc])
                    section_cards[s].add(c)

    # task index
    body = []
    used = [c for c in index_cards]
    for a, d in schema.areas.items():
        rows = index_rows[a]
        if not rows:
            continue
        body += [f"## {d['title']}", "", f"Area page: [{d['title']}](area-{a}.md).", ""]
        body += md_table(["Task", "Go to", "Status", "Not this, because"], rows) + [""]
    if used:
        pages["task-index.md"] = page(
            "Task index", ["task-index"],
            "Generated entry to the catalog: one table per area, each task in the words an agent arrives with, "
            "the part to open, its status, and why a rejected part is not the answer.",
            "Start here. Find the row that matches the task, open what Go to links, and read the part's own file in "
            "the clone. A row whose status is rejected says why it is not the answer.",
            body, used,
            [dual(f"area-{a}", d["title"], f"area-{a}.md") for a, d in schema.areas.items() if by_area[a] or
             (a == "science" and any(section_rows.values()))])

    # area pages
    for a, d in schema.areas.items():
        if a == "science":
            continue
        rows = by_area[a]
        if not rows:
            continue
        cs = sorted({r[0] for r in rows}, key=lambda c: c.slug)
        tbl = [[r[0].link("../references/"), r[1], r[2]] for r in sorted(rows, key=lambda r: (r[0].slug, r[1]))]
        nb = [n for n in d["neighbours"] if n in schema.areas and (by_area[n] or n == "science" and any(section_rows.values()))]
        links = ", ".join("[%s](area-%s.md)" % (schema.areas[n]["title"], n) for n in nb) or "none yet"
        body = [f"Neighbouring areas: {links}.", ""] + md_table(["Card", "Part", "Status"], tbl)
        pages[f"area-{a}.md"] = page(
            d["title"], [f"area-{a}"], f"Generated area page: cards and parts that serve {d['title'].lower()} tasks, with their status.",
            d["scope"], body, cs,
            [dual("task-index", "Task index", "task-index.md")] + [dual(f"area-{n}", schema.areas[n]["title"], f"area-{n}.md") for n in nb]
            + [dual(c.slug, c.title, f"../references/{c.slug}.md") for c in cs])

    # science: section list and section pages
    live = [s for s in schema.science if section_rows[s]]
    if live or by_area["science"]:
        d = schema.areas["science"]
        cs = sorted({c for s in live for c in section_cards[s]} | {r[0] for r in by_area["science"]}, key=lambda c: c.slug)
        body = ["Sections:", ""] + [f"- [{schema.science[s]['title']}](area-science-{s}.md)" for s in live]
        nb = [n for n in d["neighbours"] if n in schema.areas and by_area[n]]
        pages["area-science.md"] = page(
            d["title"], ["area-science"], "Generated area page: the science sections, each a page of parts across tools.",
            d["scope"], body, cs,
            [dual("task-index", "Task index", "task-index.md")]
            + [dual(f"area-science-{s}", schema.science[s]["title"], f"area-science-{s}.md") for s in live]
            + [dual(f"area-{n}", schema.areas[n]["title"], f"area-{n}.md") for n in nb])
        for s in live:
            rows = sorted(section_rows[s], key=lambda r: (r[1].slug, r[0].lower()))
            seen, tbl = set(), []
            for r in rows:
                k = (r[0], r[1].slug)
                if k not in seen:
                    seen.add(k)
                    tbl.append([r[0], r[1].link("../references/"), r[2], r[3]])
            scs = sorted(section_cards[s], key=lambda c: c.slug)
            t = schema.science[s]["title"]
            pages[f"area-science-{s}.md"] = page(
                f"Science: {t}", ["area-science", f"area-science-{s}"],
                f"Generated science section page: every part of every catalog tool in {t.lower()}, with its status.",
                f"Parts of science tools in the section {t.lower()}. A part whose status is listed is named from the "
                "tool's own metadata and was not read; open the card for how to run it here.",
                md_table(["Part", "Card", "Status", "One line"], tbl), scs,
                [dual("area-science", "Science", "area-science.md"), dual("task-index", "Task index", "task-index.md")]
                + [dual(c.slug, c.title, f"../references/{c.slug}.md") for c in scs])
    return pages


def first_sentence(text: str) -> str:
    m = re.match(r"(.+?[.!?])(\s|$)", " ".join(text.split()))
    return (m.group(1) if m else text).strip()


def stale(topics: Path, pages: dict[str, str]) -> list[Path]:
    if not topics.exists():
        return []
    return [p for p in sorted(topics.glob("*.md")) if p.name not in pages and MARKER in p.read_text(encoding="utf-8")]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("catalog", type=Path)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true")
    g.add_argument("--validate", nargs="*", metavar="CARD")
    args = ap.parse_args(argv)
    root = args.catalog.resolve()
    schema, cards = load(root)

    if args.validate is not None:
        chosen = cards
        if args.validate:
            want = {Path(p).resolve() for p in args.validate}
            chosen = [c for c in cards if c.path.resolve() in want]
            missing = want - {c.path.resolve() for c in chosen}
            for m in sorted(missing):
                print(f"error: not a card under {root}/wiki/references: {m}", file=sys.stderr)
            if missing:
                return 2
        bad = 0
        for c in chosen:
            for f in validate(c, schema):
                bad += 1
                print(f"{c.path.relative_to(root)}: {f}")
        print(f"{len(chosen)} card(s), {bad} finding(s)")
        return 1 if bad else 0

    pages = generate(root, schema, cards)
    topics = root / "wiki" / "topics"
    diffs = [n for n, t in pages.items() if not (topics / n).exists() or (topics / n).read_text(encoding="utf-8") != t]
    old = stale(topics, pages)
    if args.check:
        for n in diffs:
            print(f"differs: wiki/topics/{n}")
        for p in old:
            print(f"stale: wiki/topics/{p.name}")
        return 1 if diffs or old else 0
    topics.mkdir(parents=True, exist_ok=True)
    for n in diffs:
        (topics / n).write_text(pages[n], encoding="utf-8")
    for p in old:
        p.unlink()
    unmatched = sum(t.count("| unmatched |") for t in pages.values())
    print(f"{len(cards)} cards, {len(pages)} pages, {len(diffs)} written, {len(old)} removed"
          + (f", {unmatched} task rows with an unmatched part (run --validate)" if unmatched else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
